// Writes scripts/preview-art.html: every buddy × status × transition from hooks/buddies.ts + hooks/art.ts.
// Run from anywhere after editing the art: node plugins/agent-den/scripts/build-preview.mjs
// The paths come from this file's own URL, not the cwd. Node strips the TypeScript types (an experimental warning
// is fine); each hooks file runs in its own function scope, so two files may share a private name.
import { stripTypeScriptTypes } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const hooks = new URL('../hooks/', import.meta.url)
const out = new URL('./preview-art.html', import.meta.url)

// One hooks file → an IIFE that returns its exports. Imports of sibling files read from __m.
function load(name) {
  let src = stripTypeScriptTypes(readFileSync(new URL(`${name}.ts`, hooks), 'utf8'), { mode: 'strip' })
  const names = [...src.matchAll(/^export (?:const|function|let) (\w+)/gm)].map(m => m[1])
  src = src
    .replace(/^export (?=(?:const|function|let) )/gm, '')
    .replace(/^import \{([^}]*)\} from '\.\/(\w+)'.*$/gm, (_, ids, mod) => `const {${ids}} = __m.${mod}`)
    .replace(/^import .*$/gm, '')
  return `__m.${name} = (() => {\n${src}\nreturn { ${names.join(', ')} }\n})()`
}

// A `</script>` inside the art would end the page's script early; the art has none, but guard anyway.
const bundle = `const __m = {}\n${load('buddies')}\n${load('art')}`.replace(/<\/script/gi, '<\\/script')

const html = `<!-- Generated by scripts/build-preview.mjs from hooks/buddies.ts + hooks/art.ts; do not edit by hand. -->
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>agent-den art preview</title>
<style>
  :root { --panel: #0f1420; --ink: #dfe7ef; --accent: #c4b5fd; --line: rgba(223,231,239,0.18); }
  html, body { margin: 0; background: var(--panel); color: var(--ink); font: 14px/1.5 "SF Mono", Menlo, Consolas, monospace; }
  body { padding: 24px 16px 64px; }
  h1 { font-size: 18px; letter-spacing: 0.08em; text-transform: uppercase; margin: 0 0 4px; color: var(--accent); }
  h1 small { color: var(--ink); opacity: 0.6; font-weight: normal; letter-spacing: 0; text-transform: none; }
  h2 { font-size: 13px; letter-spacing: 0.12em; text-transform: uppercase; margin: 36px 0 12px; opacity: 0.8; border-bottom: 1px dashed var(--line); padding-bottom: 6px; }
  h3 { font-size: 12px; margin: 16px 0 6px; font-weight: normal; }
  button { font: inherit; background: #151c2c; color: var(--ink); border: 1px solid var(--line); border-radius: 6px; padding: 2px 10px; cursor: pointer; }
  .row { display: flex; flex-wrap: wrap; gap: 18px; align-items: flex-end; }
  .cell { display: flex; flex-direction: column; gap: 4px; align-items: center; min-width: 56px; }
  .cell svg { display: block; image-rendering: pixelated; }
  .label { font-size: 11px; opacity: 0.6; }
  pre.ascii { margin: 0; padding: 6px 8px; border: 1px solid var(--line); border-radius: 8px; line-height: 1.15; font-size: 15px; }
  .grid { display: grid; grid-template-columns: 90px repeat(7, 64px); gap: 6px 10px; align-items: center; }
  .grid .head { font-size: 11px; opacity: 0.6; text-align: center; }
  .grid .name { font-size: 12px; }
</style>
</head>
<body>
<h1>agent-den <small>art preview · buddies from hooks/buddies.ts, drawn by hooks/art.ts</small></h1>
<div id="root"></div>
<script>
${bundle}
const { ROSTER, resolveBuddy } = __m.buddies
const { buddySvg, emptyDenSvg, buddyAscii, EMPTY_DEN_ASCII, ASCII_W } = __m.art
const STATUSES = ['pending', 'running', 'waiting', 'idle', 'completed', 'failed', 'killed']
const root = document.getElementById('root')
const el = (tag, cls, html) => { const e = document.createElement(tag); if (cls) e.className = cls; if (html !== undefined) e.innerHTML = html; return e }
const h2 = text => { const h = el('h2'); h.textContent = text; root.appendChild(h) }
const cell = (inner, label) => el('div', 'cell', inner + '<div class="label">' + label + '</div>')
const row = cells => { const r = el('div', 'row'); for (const c of cells) r.appendChild(c); root.appendChild(r); return r }
const buddies = ROSTER.map(b => resolveBuddy({ key: b.key, variant: 0 }))

// 1. Every buddy × every status at 48 px (the den size).
h2('1 · Every buddy × status at 48 px')
const grid = el('div', 'grid')
grid.appendChild(el('div', 'head', ''))
for (const s of STATUSES) grid.appendChild(el('div', 'head', s))
for (const b of buddies) {
  grid.appendChild(el('div', 'name', b.displayName))
  for (const s of STATUSES) grid.appendChild(el('div', '', buddySvg(b, s, { sizePx: 48, transition: null, animations: 'full', bubble: s === 'running' ? 'thinking' : undefined })))
}
root.appendChild(grid)

// 2. Transitions per buddy, with a replay button (setting innerHTML again restarts the SMIL clock).
h2('2 · Transitions')
const replay = el('button', '', 'replay all')
root.appendChild(replay)
const plays = [['running', 'spawn'], ['completed', 'complete'], ['failed', 'fail'], ['completed', 'leave']]
const replayCells = []
for (const b of buddies) {
  const h = el('h3'); h.textContent = b.displayName; root.appendChild(h)
  row(plays.map(([s, t]) => {
    const c = cell('', s + ' + ' + t)
    const box = el('div')
    const draw = () => { box.innerHTML = buddySvg(b, s, { sizePx: 72, transition: t, animations: 'full' }) }
    draw(); replayCells.push(draw); c.prepend(box); return c
  }))
}
replay.onclick = () => replayCells.forEach(d => d())

// 3. One buddy large, every status.
h2('3 · Large: 72 px and 144 px')
for (const size of [72, 144]) row(STATUSES.map(s => cell(buddySvg(buddies[2], s, { sizePx: size, transition: null, animations: 'full' }), s + ' ' + size)))

// 4. calm and off.
h2('4 · calm and off')
for (const b of [buddies[0], buddies[6]]) for (const a of ['calm', 'off']) {
  const h = el('h3'); h.textContent = b.displayName + ' · ' + a; root.appendChild(h)
  row(STATUSES.map(s => cell(buddySvg(b, s, { sizePx: 48, transition: null, animations: a }), s)))
}

// 5. Variants.
h2('5 · Variants of Digby (hue turned 47° per step)')
row([0, 1, 2, 3, 4, 5, 6].map(n => { const v = resolveBuddy({ key: 'digby', variant: n }); return cell(buddySvg(v, 'running', { sizePx: 72, transition: null, animations: 'full' }), v.displayName) }))

// 6. The empty den.
h2('6 · Empty den')
row([cell(emptyDenSvg(96), 'emptyDenSvg(96)'), cell(emptyDenSvg(144), 'emptyDenSvg(144)'), cell('<pre class="ascii">' + EMPTY_DEN_ASCII.join('\\n') + '</pre>', 'EMPTY_DEN_ASCII')])

// 7. Terminal sprites, animated over frames 0–3 (completed hops once, then rests).
h2('7 · Terminal (' + ASCII_W + ' cells wide)')
const pres = []
for (const b of buddies) {
  const h = el('h3'); h.textContent = b.displayName; h.style.color = b.accent; root.appendChild(h)
  row(STATUSES.map(s => {
    const c = cell('<pre class="ascii"></pre>', s)
    const pre = c.querySelector('pre'); pre.style.color = s === 'failed' ? '#fb7185' : s === 'killed' ? '#8a93a6' : b.accent
    pres.push([pre, b, s]); return c
  }))
}
let frame = 0
const tick = () => { for (const [pre, b, s] of pres) pre.textContent = buddyAscii(b, s, s === 'completed' ? frame % 8 : frame, 'full').join('\\n'); frame++ }
tick(); setInterval(tick, 500)
</script>
</body>
</html>
`
writeFileSync(out, html)
console.log(`wrote ${fileURLToPath(out)}`)
