#!/usr/bin/env node
// Regenerates hooks/pricing-table.ts from pricing.json (the human-edited source of truth).
// Hooks modules cannot import JSON, so the table is shipped as a TypeScript constant.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const table = JSON.parse(readFileSync(join(root, 'pricing.json'), 'utf8'))
const out = `// GENERATED by scripts/sync-pricing.mjs from pricing.json — edit pricing.json, then run the script.
import type { PricingTable } from './pricing'

export const PRICING: PricingTable = ${JSON.stringify(table, null, 2)}
`
writeFileSync(join(root, 'hooks', 'pricing-table.ts'), out)
console.log(`wrote hooks/pricing-table.ts (asOf ${table.asOf}, ${table.models.length} models)`)
