// Writes scripts/preview-art.html: every Cog mood from hooks/art.ts on the panel colour.
// Run from the plugin folder after editing art.ts: node scripts/build-preview.mjs
import { stripTypeScriptTypes } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'

const art = stripTypeScriptTypes(readFileSync('hooks/art.ts', 'utf8'), { mode: 'strip' })
  .replace(/^export (?=(const|function|type))/gm, '')
  .replace(/^type .*$/gm, '')

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>model-advisor art preview</title>
<!-- Generated by scripts/build-preview.mjs from hooks/art.ts; do not edit by hand. -->
<style>
  :root { --panel: #0f1420; --ink: #dfe7ef; --cog: #a9c4e4; }
  html, body { margin: 0; background: var(--panel); color: var(--ink); font: 14px/1.5 "SF Mono", Menlo, Consolas, monospace; }
  body { padding: 24px 16px 64px; }
  h1 { font-size: 18px; letter-spacing: 0.08em; text-transform: uppercase; margin: 0 0 4px; color: var(--cog); }
  h1 small { color: var(--ink); opacity: 0.6; font-weight: normal; letter-spacing: 0; text-transform: none; }
  h2 { font-size: 13px; letter-spacing: 0.12em; text-transform: uppercase; margin: 36px 0 12px; opacity: 0.8; border-bottom: 1px dashed rgba(230,241,255,0.25); padding-bottom: 6px; }
  .row { display: flex; flex-wrap: wrap; gap: 24px; align-items: flex-end; }
  .cell { display: flex; flex-direction: column; gap: 6px; align-items: center; }
  .cell svg { display: block; image-rendering: pixelated; }
  .label { font-size: 11px; opacity: 0.65; }
  pre.ascii { margin: 0; padding: 8px 10px; border: 1px solid rgba(223,231,239,0.25); border-radius: 8px; display: inline-block; line-height: 1.15; font-size: 16px; color: var(--cog); }
</style>
</head>
<body>
<h1>model-advisor <small>art preview · Cog from hooks/art.ts on the panel colour</small></h1>
<div id="root"></div>
<script>
${art}
const root = document.getElementById('root')
const section = (title, cells) => {
  const h = document.createElement('h2'); h.textContent = title; root.appendChild(h)
  const row = document.createElement('div'); row.className = 'row'; root.appendChild(row)
  for (const [inner, label] of cells) {
    const c = document.createElement('div'); c.className = 'cell'
    c.innerHTML = inner + '<div class="label">' + label + '</div>'
    row.appendChild(c)
  }
}
const moods = ['idle', 'reading', 'down', 'up', 'fit']
section('Cog at 44px (band size)', moods.map(m => [cogSvg(m, 44), m]))
section('Cog at 160px', moods.map(m => [cogSvg(m, 160), m]))
for (const frame of [0, 1]) {
  section('Terminal, frame ' + (frame + 1), moods.map(m => ['<pre class="ascii">' + COG_ASCII[m][frame].join('\\n') + '</pre>', m]))
}
</script>
</body>
</html>
`
writeFileSync('scripts/preview-art.html', html)
